function slug(value: string) {
  return value.normalize("NFD").replace(/[\u0300-\u036f]/g, "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

export const drinkCategories: MenuCategory[] = groups.map((group, order) => ({
  id: group.id, kind: "drink", label: { es: group.label, en: group.english, ...categoryTranslations[group.id] }, parentId: null, order,
}));

export const drinkProducts: MenuProduct[] = groups.flatMap((group) => group.rows.map(([name, priceCents]) => ({
  id: `${group.id}-${slug(name)}`,
  kind: "drink" as const,
  categoryId: group.id,
  name: { es: name },
  description: null,
  priceCents,
  currency: "EUR" as const,
  image: null,
  ingredients: null,
  allergens: null,
  availability: "unknown" as const,
  additionalInformation: null,
  origin: "provided" as const,
  sourceUrl: null,
})));
